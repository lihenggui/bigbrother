package li.mercury.bigbrother.feature.settings.impl

import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.selection.selectableGroup
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.AlertDialog
import androidx.compose.material3.ExperimentalMaterial3ExpressiveApi
import androidx.compose.material3.ListItem
import androidx.compose.material3.ListItemDefaults
import androidx.compose.material3.RadioButton
import androidx.compose.material3.Text
import androidx.compose.material3.TextButton
import androidx.compose.runtime.Composable
import androidx.compose.ui.Modifier
import androidx.compose.ui.res.stringResource
import androidx.compose.ui.semantics.Role
import androidx.compose.ui.semantics.role
import androidx.compose.ui.semantics.semantics
import li.mercury.bigbrother.core.model.ThemeMode

internal val ThemeMode.label: Int
    get() = when (this) {
        ThemeMode.SYSTEM -> R.string.theme_system
        ThemeMode.LIGHT -> R.string.theme_light
        ThemeMode.DARK -> R.string.theme_dark
    }

@OptIn(ExperimentalMaterial3ExpressiveApi::class)
@Composable
internal fun ThemeModeDialog(mode: ThemeMode, onDismiss: () -> Unit, onSelect: (ThemeMode) -> Unit) {
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text(stringResource(R.string.theme)) },
        text = {
            Column(Modifier.selectableGroup().verticalScroll(rememberScrollState())) {
                ThemeMode.entries.forEachIndexed { index, option ->
                    ListItem(
                        selected = mode == option,
                        onClick = { onSelect(option) },
                        modifier = Modifier.fillMaxWidth().semantics { role = Role.RadioButton },
                        shapes = ListItemDefaults.segmentedShapes(index, ThemeMode.entries.size),
                        colors = ListItemDefaults.segmentedColors(),
                        leadingContent = { RadioButton(selected = mode == option, onClick = null) },
                    ) {
                        Text(stringResource(option.label))
                    }
                }
            }
        },
        confirmButton = { TextButton(onClick = onDismiss) { Text(stringResource(R.string.cancel)) } },
    )
}
